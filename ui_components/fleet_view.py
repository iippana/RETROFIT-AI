    card_cols = st.columns(3)
    for idx, (_, row) in enumerate(filtered.iterrows()):
        col = card_cols[idx % 3]
        tier_info = TIER_COLORS.get(row["instrumentation_tier"], {"label": row["instrumentation_tier"], "bg": "#f8f9fa", "fg": "#333", "border": "#ccc"})
        split_color = SPLIT_COLORS.get(row["split"], "#333")

        # Count events & AI predictions for this pump
        pump_events = events[events["asset_id"] == row["asset_id"]] if not events.empty else pd.DataFrame()
