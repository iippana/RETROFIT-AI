"""Module 1: Fleet Overview & Sensor Tier Dashboard.

Displays high-level KPI metrics across all 12 cooling-water pumps,
filterable cards with instrumentation tiers, operating modes, hardware specs,
and active AI diagnostic alerts, plus an instrumentation capability matrix.
"""
