        {"Signal / Capability": "Strainer Clogging Detection", "T0 Legacy": "⚠️ Late (via drive power/head loss)", "T1 Retrofit (€2.4k)": "🎯 Immediate (ΔP suction drop)", "T2 Full (€8k+)": "🎯 Immediate + Flow confirmation"},
