                if row["split"] == "test":
                    if len(pump_preds) > 0:
                        ft_list = ", ".join(sorted(pump_preds["fault_type"].unique())[:2])
                        st.info(f"🔒 Test Set · 🧠 **{len(pump_preds)} AI Alerts** (`{ft_list}`)")
                    else:
                        st.info("🔒 Test Set: Ground-truth blinded")
