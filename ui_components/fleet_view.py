    if tier_filter != "All":
        filtered = filtered[filtered["instrumentation_tier"] == tier_filter]
    if profile_filter != "All":
        filtered = filtered[filtered["profile"] == profile_filter]
    if site_filter != "All":
        filtered = filtered[filtered["site"] == site_filter]

